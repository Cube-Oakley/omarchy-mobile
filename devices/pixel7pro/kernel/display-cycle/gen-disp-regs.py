"""Generate pixel-disp-regs.h: every register Google's GS201 display headers
define for the blocks pixel-disp-cycle checks, so a power cycle's readback
can be compared register by register. Read-only use: the module only reads
this list. FIFO and packet registers (reading pops data) and the secure
ones (TZPC-protected; a non-secure read can fault) are left out.

Input: Google's display modules (kernel/google-modules/display @ 0137241),
samsung/cal_9845/regs-{dsim,decon,dpp}.h, GPL-2.0-only.

Usage: gen-disp-regs.py CAL_9845_DIR [-o pixel-disp-regs.h]
"""
import argparse
import re

PLAIN = re.compile(r"^#define\s+([A-Z][A-Z0-9_]*)\s+\((0x[0-9A-Fa-f]+)\)\s*(?://.*|/\*.*)?$")
SKIP = re.compile(r"FIFO|PKTHDR|PAYLOAD|RXFIFO|DEBUG_DATA|SECURE|SECURITY|TZPC")
# Block offsets, not registers; RDMA_SRC_OFFSET and RDMA_BLOCK_OFFSET are registers.
NOT_REGS = re.compile(r"_OFFSET$")
REAL_OFFSETS = {"RDMA_SRC_OFFSET", "RDMA_BLOCK_OFFSET"}
# DSIM link registers despite their prefix (regs-dsim.h:361-362).
DSIM_LINK = {"DSIM_PHY_CTRL", "DSIM_PHY_TIMING"}


def plain(path, prefix, limit):
    out = []
    with open(path) as f:
        for line in f:
            m = PLAIN.match(line.strip())
            if not m or not m.group(1).startswith(prefix) or SKIP.search(m.group(1)):
                continue
            if NOT_REGS.search(m.group(1)) and m.group(1) not in REAL_OFFSETS:
                continue
            off = int(m.group(2), 16)
            if off < limit and off % 4 == 0:
                out.append((off, m.group(1)))
    return sorted(set(out))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cal")
    ap.add_argument("-o", "--output", default="pixel-disp-regs.h")
    a = ap.parse_args()
    rows = []
    rows += [("DSIM", o, n) for o, n in plain(f"{a.cal}/regs-dsim.h", "DSIM_", 0x300)
             if not n.startswith("DSIM_PHY") or n in DSIM_LINK]
    rows += [("PHY", o, n) for o, n in plain(f"{a.cal}/regs-dsim.h", "DSIM_PHY_", 0x700)
             if n not in DSIM_LINK]
    rows += [("BIAS", 4 * i, f"DSIM_PHY_BIAS_CON{i}") for i in range(5)]
    rows += [("PHY", 0x300 + 0x100 * lane + o, f"MD{lane}_{n}") for lane in range(4)
             for o, n in ((0x0, "GNR_CON0"), (0x4, "GNR_CON1"), (0x8, "ANA_CON0"), (0xc, "ANA_CON1"),
                          (0x10, "ANA_CON2"), (0x14, "ANA_CON3"), (0x30, "TIME_CON0"), (0x34, "TIME_CON1"),
                          (0x38, "TIME_CON2"), (0x3c, "TIME_CON3"), (0x40, "TIME_CON4"))]
    rows += [("DECON", o, n) for o, n in plain(f"{a.cal}/regs-decon.h", "", 0x6000)]
    for w in range(6):
        rows += [("WIN", 0x1000 * w + o, f"WIN{w}_{n}") for o, n in
                 ((0x4, "FUNC_CON_0"), (0x8, "FUNC_CON_1"), (0xc, "START_POSITION"), (0x10, "END_POSITION"),
                  (0x14, "COLORMAP_0"), (0x18, "COLORMAP_1"), (0x1c, "START_TIME_CON"))]
        rows.append(("WINCON", 0x1000 * w, f"DECON_CON_WIN{w}"))
    for d in range(2):
        rows += [("SUB", 0x1000 * d + o, f"DSC{d}_{n}") for o, n in
                 [(0x0, "CONTROL_0"), (0x4, "CONTROL_1"), (0xc, "CONTROL_3")] +
                 [(0x20 + 4 * i, f"PPS{4 * i:02d}_{4 * i + 3:02d}") for i in range(22)]]
    rows += [("SUB", 0x8000, "DSIMIF0_SEL"), ("SUB", 0x9000, "DSIMIF1_SEL")]
    rows += [("DMA", o, n) for o, n in plain(f"{a.cal}/regs-dpp.h", "RDMA_", 0x800)]
    # Only the common block: L0 may lack the scaler and HDR sub-blocks.
    rows += [("DPP", o, n) for o, n in plain(f"{a.cal}/regs-dpp.h", "DPP_COM_", 0x1000)]
    out = ["/* SPDX-License-Identifier: GPL-2.0-only */",
           "/* Generated by gen-disp-regs.py from Google's cal_9845 register headers",
           " * (kernel/google-modules/display @ 0137241). Do not edit. */",
           "#ifndef PIXEL_DISP_REGS_H", "#define PIXEL_DISP_REGS_H", "",
           "static const struct disp_reg disp_regs[] = {"]
    out += [f"\t{{ BLK_{b}, {o:#06x}, \"{n}\" }}," for b, o, n in rows]
    out += ["};", "", "#endif"]
    with open(a.output, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(rows)} registers")


if __name__ == "__main__":
    main()
